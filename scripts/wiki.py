#!/usr/bin/env python3
"""Build and publish the GitHub wiki from wiki/ in this repository.

    python scripts/wiki.py build      # regenerate the generated pages in wiki/
    python scripts/wiki.py check      # every [[page]] / (Page) link resolves; generated pages current
    python scripts/wiki.py publish    # push wiki/ to github.com/EdWelsh/AUTON.wiki.git

The wiki's source of truth is wiki/ here, reviewed like any change; the GitHub
wiki is a copy. Pages that restate data (the specialist roster, the numbers on
Home) are generated from that data, so they cannot drift from it.

Publishing needs write access to the repository, and GitHub creates the wiki's
git repository only after its first page is saved in the web UI: create any page
once at https://github.com/EdWelsh/AUTON/wiki, then publish.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
WIKI = ROOT / "wiki"
WIKI_REMOTE = "https://github.com/EdWelsh/AUTON.wiki.git"
REPO_URL = "https://github.com/EdWelsh/AUTON/blob/HEAD/"
GENERATED = "<!-- generated by scripts/wiki.py build: edit the data, not this page -->"


def specialists_page() -> str:
    data = yaml.safe_load((ROOT / "agent/kernel_spec/specialists.yaml").read_text())
    rows = []
    for s in data["specialists"]:
        pool = f"{s['id'].replace('-', '_')}_specialist"
        specs = ", ".join(f"`{x}`" for x in s["specs"])
        files = ", ".join(f"`{f}`" for f in s["files"][:3])
        rows.append(f"| **{s['title']}** | `{pool}` | {specs} | {files} | {len(s['checklist'])} |")
    detail = []
    for s in data["specialists"]:
        items = "\n".join(f"- {c}" for c in s["checklist"])
        detail.append(f"### {s['title']}\n\n{' '.join(s['focus'].split())}\n\n"
                      f"**Review checklist**\n\n{items}\n")
    return f"""{GENERATED}
# Specialists

One specialist per aspect of kernel creation, defined as data in
[`agent/kernel_spec/specialists.yaml`]({REPO_URL}agent/kernel_spec/specialists.yaml). Each is
a Developer with its area's specs, knowledge and checklist in its prompt; the manager assigns
work to its pool name. Every reviewer receives the checklist of each specialist whose files a
change touches. Enabled with `agents.specialists = "all"` (the example config) or a list of ids.

**{len(data['specialists'])} specialists.** A test fails if any names a spec that does not exist.

| Specialist | Pool | Specs it owns | Files it covers | Checklist items |
|---|---|---|---|---|
{chr(10).join(rows)}

{chr(10).join(detail)}
See also: [Agents and Swarms](Agents-and-Swarms) · [Kernel Specs](Kernel-Specs)
"""


def numbers() -> dict:
    reg = json.loads((ROOT / "agent/hardware/registry/vendors.json").read_text())
    isa = {a: json.loads((ROOT / f"agent/hardware/isa/{a}.json").read_text())
           for a in ("x86", "aarch64", "riscv", "powerpc", "systemz")}
    qemu = json.loads((ROOT / "agent/hardware/isa/qemu.json").read_text())
    spec = yaml.safe_load((ROOT / "agent/kernel_spec/specialists.yaml").read_text())
    count = lambda p: sum(1 for _ in open(ROOT / p, encoding="utf-8"))  # noqa: E731
    return {
        "vendors": reg["count"],
        "covered": sum(1 for e in reg["vendors"] if e["inventory"]),
        "processors": sum(len(t["processors"]) for t in isa.values()),
        "qemu_models": len(qemu["models"]),
        "specialists": len(spec["specialists"]),
        "gates": len(list((ROOT / "tests/kernel").glob("run_*_test.sh"))),
        "chat_rows": count("SLM/datasets/os_chat.jsonl"),
        "cpu_rows": count("SLM/datasets/hardware_kernel.jsonl"),
        "ref_rows": count("SLM/datasets/hardware_reference.jsonl"),
    }


def numbers_block() -> str:
    n = numbers()
    return f"""{GENERATED}
| | |
|---|---|
| Host gate suites | **{n['gates']}** in `tests/kernel/` |
| Specialist agents | **{n['specialists']}** |
| Hardware vendors in the registry | **{n['vendors']:,}** ({n['covered']} with document coverage) |
| Processor models with instruction tables | **{n['processors']}** across 5 architectures, plus {n['qemu_models']} QEMU CPU models |
| Kernel SLM training set | **{n['chat_rows'] + n['cpu_rows']:,} rows** (chat {n['chat_rows']}, CPU {n['cpu_rows']}) |
| Host-side hardware reference corpus | **{n['ref_rows']:,} rows** |
"""


NUMBERS = ("<!-- numbers -->", "<!-- /numbers -->")


def numbers_span(home: str) -> tuple[int, int] | None:
    """Where the generated numbers sit in Home.md's text, or None without the markers."""
    start, end = NUMBERS
    if start not in home or end not in home:
        return None
    return home.index(start) + len(start), home.index(end)


def build() -> None:
    (WIKI / "Specialists.md").write_text(specialists_page())
    home = (WIKI / "Home.md").read_text()
    if span := numbers_span(home):
        a, b = span
        home = home[:a] + "\n" + numbers_block() + home[b:]
        (WIKI / "Home.md").write_text(home)
    print(f"built {WIKI.relative_to(ROOT)}: Specialists.md, Home.md numbers")


def pages() -> dict[str, Path]:
    return {p.stem: p for p in WIKI.glob("*.md")}


def check() -> int:
    have = pages()
    bad = []
    for name, p in have.items():
        text = re.sub(r"```.*?```", "", p.read_text(), flags=re.S)   # code is not links
        targets = [m.group(1) for m in re.finditer(r"\[\[(?:[^|\]]*\|)?([^\]]+)\]\]", text)]
        # [Text](Page-Name): a wiki page when the target has no scheme, path or extension
        targets += [m.group(1) for m in re.finditer(r"\]\(([A-Za-z][\w-]*)\)", text)]
        for t in targets:
            target = t.strip().replace(" ", "-")
            if target not in have:
                bad.append(f"{name}: link to {t!r} -> no page {target}")
    stale = []
    if (WIKI / "Specialists.md").read_text() != specialists_page():
        stale.append("Specialists.md")
    home = (WIKI / "Home.md").read_text()
    if (span := numbers_span(home)) and home[span[0]:span[1]] != "\n" + numbers_block():
        stale.append("Home.md")
    for b in bad:
        print(b)
    for s in stale:
        print(f"{s} is stale: run python scripts/wiki.py build")
    print(f"{len(have)} pages; {len(bad)} broken links; {len(stale)} stale generated pages")
    return 1 if bad or stale else 0


def publish() -> int:
    if check():
        return 1
    dest = ROOT / ".artifacts" / "wiki"
    if dest.exists():
        shutil.rmtree(dest)
    r = subprocess.run(["git", "clone", "--depth", "1", WIKI_REMOTE, str(dest)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"could not clone {WIKI_REMOTE}: {r.stderr.strip()}\n"
              f"Create the wiki's first page at https://github.com/EdWelsh/AUTON/wiki, and make "
              f"sure this machine can push to the repository.", file=sys.stderr)
        return 2
    for old in dest.glob("*.md"):
        old.unlink()
    for p in WIKI.glob("*.md"):
        shutil.copy(p, dest / p.name)
    subprocess.run(["git", "-C", str(dest), "add", "-A"], check=True)
    if subprocess.run(["git", "-C", str(dest), "diff", "--cached", "--quiet"]).returncode == 0:
        print("wiki already up to date")
        return 0
    head = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    subprocess.run(["git", "-C", str(dest), "commit", "-q", "-m",
                    f"Sync wiki from AUTON {head} (scripts/wiki.py publish)"], check=True)
    return subprocess.run(["git", "-C", str(dest), "push", "origin", "HEAD"]).returncode


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "build":
        build()
        raise SystemExit(0)
    if cmd == "check":
        raise SystemExit(check())
    if cmd == "publish":
        raise SystemExit(publish())
    print(__doc__)
    raise SystemExit(2)
