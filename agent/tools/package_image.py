"""Assemble an intent into a reviewable package.

    AUTON train "I want to host this repo" --output ./repo-host

`<output>/` carries the ISO, the scoped model, the spec subset that generated
it, an installer, and a provenance record.

The PRD's reason for provenance is specific: *"a human must be able to review
generated kernel code without reading it blind."* That means the record has to
say **which spec section each artifact implements**, not merely list files. A
file listing with hashes is a manifest; this is meant to be a review aid.

An intent that cannot be built yet produces a package that **says so**. A
directory missing its ISO looks like a build that half-worked rather than one
that was never possible, and the difference matters to whoever opens it next.
"""

